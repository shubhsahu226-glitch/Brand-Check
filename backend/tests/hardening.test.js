import { describe, it, expect } from 'vitest';
import request from 'supertest';
import app from '../src/app';
import {
  hashToken,
  generateRandomToken,
  generateAccessToken,
  verifyAccessToken,
  getJwtSecret,
} from '../src/lib/tokens';
import { AppError } from '../src/lib/errors';

describe('Step 3: Crypto utilities, error envelope, and app hardening', () => {
  describe('Crypto and Token utilities', () => {
    it('hashToken produces consistent sha256 hex string', () => {
      const raw = 'my-test-token-123';
      const hash1 = hashToken(raw);
      const hash2 = hashToken(raw);
      expect(hash1).toBe(hash2);
      expect(hash1).toHaveLength(64); // sha256 is 32 bytes = 64 hex characters
      expect(hash1).toMatch(/^[a-f0-9]{64}$/);
    });

    it('generateRandomToken produces cryptographically random hex string', () => {
      const token1 = generateRandomToken(64);
      const token2 = generateRandomToken(64);
      expect(token1).not.toBe(token2);
      expect(token1).toHaveLength(128); // 64 bytes = 128 hex characters
      expect(token2).toHaveLength(128);

      const token32 = generateRandomToken(32);
      expect(token32).toHaveLength(64); // 32 bytes = 64 hex characters
    });

    it('generateAccessToken and verifyAccessToken encode and decode payload', () => {
      const payload = { userId: 'user-cuid-123', email: 'test@brandcheck.io' };
      const token = generateAccessToken(payload);
      expect(typeof token).toBe('string');

      const decoded = verifyAccessToken(token);
      expect(decoded.userId).toBe('user-cuid-123');
      expect(decoded.email).toBe('test@brandcheck.io');
      expect(decoded.exp).toBeDefined();
    });

    it('getJwtSecret refuses to run in production if secret is missing or < 32 chars', () => {
      const originalEnv = process.env.NODE_ENV;
      const originalSecret = process.env.JWT_ACCESS_SECRET;

      process.env.NODE_ENV = 'production';
      process.env.JWT_ACCESS_SECRET = 'short-secret';
      expect(() => getJwtSecret()).toThrow(/at least 32 characters/);

      delete process.env.JWT_ACCESS_SECRET;
      expect(() => getJwtSecret()).toThrow(/at least 32 characters/);

      // Restore
      process.env.NODE_ENV = originalEnv;
      process.env.JWT_ACCESS_SECRET = originalSecret;
    });
  });

  describe('HTTP App Hardening & Security Headers', () => {
    it('sets security headers via Helmet and returns X-Request-Id header', async () => {
      const res = await request(app).get('/api/health');
      expect(res.status).toBe(200);

      // Helmet security headers
      expect(res.headers['x-content-type-options']).toBe('nosniff');
      expect(res.headers['x-frame-options']).toBeDefined();

      // X-Request-Id header generated by pino-http
      expect(res.headers['x-request-id']).toBeDefined();
      expect(res.headers['x-request-id'].length).toBeGreaterThan(0);
    });

    it('passes through incoming X-Request-Id header', async () => {
      const customId = 'req-custom-trace-id-999';
      const res = await request(app)
        .get('/api/health')
        .set('X-Request-Id', customId);

      expect(res.headers['x-request-id']).toBe(customId);
    });

    it('GET /api/health reports database status', async () => {
      const res = await request(app).get('/api/health');
      expect(res.status).toBe(200);
      expect(res.body.service).toBe('brandcheck-backend');
      expect(['connected', 'disconnected']).toContain(res.body.database);
    });
  });

  describe('Standardized Error Envelope and 404 Handler', () => {
    it('returns standardized error envelope on 404', async () => {
      const res = await request(app).get('/api/non-existent-route-xyz');
      expect(res.status).toBe(404);
      expect(res.body).toEqual({
        error: {
          code: 'NOT_FOUND',
          message: 'Cannot GET /api/non-existent-route-xyz',
        },
      });
    });

    it('returns standardized error envelope for AppError', () => {
      const err = new AppError(403, 'FORBIDDEN', 'Access denied');
      expect(err.status).toBe(403);
      expect(err.code).toBe('FORBIDDEN');
      expect(err.message).toBe('Access denied');
    });
  });
});
